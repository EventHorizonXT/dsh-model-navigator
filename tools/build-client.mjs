/**
 * 生成 lib/client.js。
 *
 * 关键点：三级界面的纯逻辑（src/core/*.mjs，有单测覆盖）不是手抄到客户端，
 * 而是由本脚本去掉 export 关键字后原样内联进产物，避免两份实现漂移。
 * 宿主的模块加载器直接运行现代语法（官方客户端包同样如此），因此不再转译。
 * 客户端模板 src/client/client.template.js 只保留：宿主 I/O、slot 注册、React 组件、样式、词条。
 *
 * 用法：node tools/build-client.mjs [--with-embeds]
 *   总是写正式产物 lib/client.js（**不带**探针）；--with-embeds 再额外写一份
 *   lib/client.with-embeds.js，把 __core 挂到 window.__DSH_MODEL_NAVIGATOR_CORE__，
 *   供 tests/client-surface.test.mjs 与 src/core 的 ESM 版本对拍。发布物只用 lib/client.js。
 */
import { readFile, writeFile, readdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const coreDir = join(root, "src", "core");
const templateFile = join(root, "src", "client", "client.template.js");
const outDir = join(root, "lib");
const outFile = join(outDir, "client.js");
const probeFile = join(outDir, "client.with-embeds.js");
const withEmbeds = process.argv.includes("--with-embeds");

/** src/core 的内联顺序（模块之间没有 import，顺序只影响产物的可读性）。 */
const ORDER = ["identity", "classify", "search", "sort", "draft", "preferences"];

const DECLARATION = /^(export\s+)?(?:async\s+)?(?:function\*?|const|let|var|class)\s+([A-Za-z_$][\w$]*)/gm;

/** 模块的导出名（只支持 `export function|const|let|var|class NAME` 这一种写法）。 */
function exportedNames(source) {
  const names = [];
  for (const match of source.matchAll(DECLARATION)) if (match[1] !== undefined) names.push(match[2]);
  return names;
}

/** 顶层声明名（导出与否都算）：所有模块共享同一个作用域，重名必须在构建期拦下。 */
function topLevelNames(source) {
  return Array.from(source.matchAll(DECLARATION), (match) => match[2]);
}

/** 去掉 export 关键字；遇到内联后无法成立的模块语法直接失败。 */
function inlineModule(source, file) {
  if (/^\s*import\s/m.test(source)) throw new Error(`${file}: src/core modules must not import (they are inlined into one scope)`);
  if (/^\s*export\s+(?:default\b|\{|\*)/m.test(source)) throw new Error(`${file}: only "export function|const|let|var|class NAME" is supported`);
  return source.replace(/^export\s+/gm, "");
}

const files = await readdir(coreDir);
const present = files.filter((file) => file.endsWith(".mjs")).map((file) => file.replace(/\.mjs$/, ""));
for (const entry of ORDER) if (!present.includes(entry)) throw new Error(`src/core is missing ${entry}.mjs`);
for (const entry of present) if (!ORDER.includes(entry)) throw new Error(`src/core/${entry}.mjs is not listed in ORDER`);

const chunks = [];
const surfaceNames = [];
const declaredIn = new Map();
for (const entry of ORDER) {
  const file = `src/core/${entry}.mjs`;
  const source = await readFile(join(coreDir, `${entry}.mjs`), "utf8");
  for (const name of topLevelNames(source)) {
    if (declaredIn.has(name)) throw new Error(`${file}: top-level "${name}" is already declared in ${declaredIn.get(name)}`);
    declaredIn.set(name, file);
  }
  const body = inlineModule(source, file).trimEnd().replace(/^(?=.)/gm, "      ");
  chunks.push(`      /* ==== ${file} — generated by tools/build-client.mjs, do not edit ==== */\n${body}`);
  surfaceNames.push(...exportedNames(source));
}

const pkg = JSON.parse(await readFile(join(root, "package.json"), "utf8"));

/** 生成内联块。withProbe 决定是否把 __core 暴露到 window（只给测试用）。 */
function renderEmbedded(withProbe) {
  // 独立函数作用域：core 的 const/let 不会与模板里的 var / function 同名冲突。
  return [
    "    var __core = (function () {",
    "      \"use strict\";",
    chunks.join("\n\n"),
    "",
    "      return {",
    "        __withEmbeds: " + (withProbe ? "true" : "false") + ",",
    surfaceNames.map((name) => `        ${name}: ${name}`).join(",\n"),
    "      };",
    "    })();",
    withProbe ? "    window.__DSH_MODEL_NAVIGATOR_CORE__ = __core;" : ""
  ].filter((line) => line !== "").join("\n");
}

const templateSource = await readFile(templateFile, "utf8");

function render(withProbe) {
  for (const marker of ["/*__CORE_EMBED__*/", '/*__VERSION__*/"dev"']) {
    if (!templateSource.includes(marker)) throw new Error(`template is missing the ${marker} marker`);
  }
  return templateSource
    .replace("/*__CORE_EMBED__*/", () => renderEmbedded(withProbe))
    .replace('/*__VERSION__*/"dev"', () => JSON.stringify(pkg.version));
}

// 正式产物永远是不带探针的那一份（发布物里不该出现 window.__DSH_MODEL_NAVIGATOR_CORE__）。
// --with-embeds 只是**额外**再写一份测试用探针包：这样「改完 src/core 后跑 --with-embeds」
// 既不会把 lib/client.js 留在旧版本上（测试读的正是 lib/client.js），也不会把探针塞进正式产物。
const shipped = render(false);
const written = [];
await writeFile(outFile, shipped, "utf8");
written.push(`lib/client.js (${Buffer.byteLength(shipped)} bytes, embeds=false)`);
if (withEmbeds) {
  const probe = render(true);
  await writeFile(probeFile, probe, "utf8");
  written.push(`lib/client.with-embeds.js (${Buffer.byteLength(probe)} bytes, embeds=true)`);
}
console.log(`built ${written.join(" + ")} (version=${pkg.version}, exported surface=${surfaceNames.length})`);
